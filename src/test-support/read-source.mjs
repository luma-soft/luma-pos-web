import { readFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const webSrc = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const backendSrc = path.resolve(webSrc, "../vendor/backend/src");

/**
 * Source text for tests that check code by reading it: a path relative to the
 * test file, looked up in the web first, then in the backend submodule
 * (vendor/backend), like the @/* import fallback.
 */
export function readSource(relativePath, testUrl) {
  const url = new URL(relativePath, testUrl);
  try {
    const text = readFileSync(url, "utf8");
    // Generated proxies stand in for backend modules; tests mean the backend code.
    if (!text.startsWith("\"use server\";\n\n// Generated by luma-pos-backend") && !text.startsWith("// Generated by luma-pos-backend")) return text;
    throw Object.assign(new Error("generated proxy"), { code: "ENOENT" });
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
    const inWeb = path.relative(webSrc, fileURLToPath(url));
    if (inWeb.startsWith("..")) throw error;
    return readFileSync(path.join(backendSrc, inWeb), "utf8");
  }
}
